/**
 * Regenerates src/instrument.generated.ts from package.json and the resolved lockfile.
 *
 * The versions are baked in rather than read at run time because neither parse5 nor the
 * package itself exposes its version to an importer, and reading package.json through an
 * exports map is not portable. CI regenerates this file and fails if it differs from the
 * committed copy, so it cannot drift from the dependency tree it describes.
 *
 * The commit is deliberately absent: a file committed in the same commit cannot record
 * that commit's own hash. Provenance for a run is fixed by the evaluation tag instead.
 */

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkg = require('../package.json');

/**
 * Reads a dependency's own version. Not via `require('<name>/package.json')`: parse5 and
 * others do not expose that subpath in their exports map. Resolving the entry point and
 * walking up to the manifest works whatever the install layout.
 */
function versionOf(name) {
  let dir = dirname(require.resolve(name));
  for (;;) {
    const candidate = join(dir, 'package.json');
    try {
      const manifest = JSON.parse(readFileSync(candidate, 'utf8'));
      if (manifest.name === name) return manifest.version;
    } catch {
      // Keep walking: nested directories need not carry a manifest.
    }
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`could not resolve a manifest for ${name}`);
    dir = parent;
  }
}

const RECORDED = ['parse5', 'axe-core'];
const dependencies = Object.fromEntries(RECORDED.map((name) => [name, versionOf(name)]));

const body = `/**
 * Generated by scripts/write-instrument.mjs. Do not edit by hand.
 *
 * Run \`npm run instrument\` after changing package.json or the lockfile. CI verifies
 * that this file matches the installed tree.
 */

export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};

export const DEPENDENCY_VERSIONS: Readonly<Record<string, string>> = Object.freeze(
${JSON.stringify(dependencies, null, 2)
  .split('\n')
  .map((line) => `  ${line}`)
  .join('\n')}
);
`;

writeFileSync(new URL('../src/instrument.generated.ts', import.meta.url), body);
console.log(`instrument: formfair ${pkg.version}, ${JSON.stringify(dependencies)}`);
